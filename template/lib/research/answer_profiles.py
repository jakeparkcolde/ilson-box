def choose_profile(question):
    if is_flight_question(question): return 'travel'
    # 추가 LLM 호출 없이 분류한다. 비교 의도가 명시되면 비교 구성을 우선한다.
    patterns=[('review',r'실사용|사용\s*후기|장기\s*후기|리뷰|\breviews?\b'),('comparison',r'차이|비교|\bvs\b'),('howto',r'방법|사용법|예제|코드.*(?:작성|보여)|설치|설정|만들|구현'),('recommendation',r'추천|저렴|사야|구매|고르|선택'),('concept',r'이란|란\?|무엇|뭐야|뜻|개념')]
    return next((name for name,pattern in patterns if re.search(pattern,question,re.I)),'research')

